import type { LocalizedText } from '../i18n/types';
import type {
  UnitCost,
  UnitDefinition,
  UnitDomain,
  UnitRole,
  UnitStats,
  UnitVisualSpec,
} from '../gameplay/military/types';

/**
 * Data-driven unit catalogue.
 *
 * Only data lives here — the combat resolver, production queue and army AI read
 * these definitions generically. Adding a hundred more vehicles means adding a
 * hundred entries, never new code. Each entry has a unique visual `variant` so
 * the model factory can build a distinct silhouette from the same generator.
 */

interface UnitSpec {
  id: string;
  name: LocalizedText;
  description?: LocalizedText;
  domain: UnitDomain;
  role: UnitRole;
  tier: number;
  stats: Partial<UnitStats>;
  cost: Partial<UnitCost>;
  buildDays: number;
  manpower: number;
  upkeep: number;
  requiresTech?: string[];
  strong?: string[];
  weak?: string[];
  visual: UnitVisualSpec;
}

