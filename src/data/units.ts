export const UNITS: Record<string, UnitDefinition> = Object.fromEntries(
  UNIT_SPECS.map((spec) => {
    const unit = defineUnit(spec);
    return [unit.id, unit];
  }),
);

export const UNIT_LIST: UnitDefinition[] = UNIT_SPECS.map(defineUnit);

export const getUnit = (id: string): UnitDefinition | undefined => UNITS[id];

export const unitsByDomain = (domain: UnitDomain): UnitDefinition[] =>
  UNIT_LIST.filter((unit) => unit.domain === domain);

export const unitsByRole = (role: UnitRole): UnitDefinition[] =>
  UNIT_LIST.filter((unit) => unit.role === role);

/** Composite power used for AI strength estimates and UI strength bars. */
export const unitPower = (unit: UnitDefinition): number =>
  unit.stats.attack * 0.5 +
  unit.stats.hardAttack * 0.6 +
  unit.stats.defence * 0.4 +
  unit.stats.health * 0.12 +
  unit.stats.armor * 60 +
  unit.stats.speed * 0.04;
