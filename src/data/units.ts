const palette = (primary: string, secondary: string, accent: string) => ({
  primary,
  secondary,
  accent,
});

const defineUnit = (spec: UnitSpec): UnitDefinition => ({
  id: spec.id,
  name: spec.name,
  description: spec.description,
  domain: spec.domain,
  role: spec.role,
  tier: spec.tier,
  stats: { ...BASE_STATS, ...spec.stats },
  cost: { ...BASE_COST, ...spec.cost },
  buildDays: spec.buildDays,
  manpower: spec.manpower,
  upkeep: spec.upkeep,
  requiresTech: spec.requiresTech ?? [],
  strongAgainst: spec.strong ?? [],
  weakAgainst: spec.weak ?? [],
  visual: spec.visual,
});

